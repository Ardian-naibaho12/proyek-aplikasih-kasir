// Helper to generate realistic dates relative to recent days
const getPastDateISO = (daysAgo: number, hour = 10, minute = 30): string => {
  const d = new Date('2026-11-04T12:00:00Z');
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

